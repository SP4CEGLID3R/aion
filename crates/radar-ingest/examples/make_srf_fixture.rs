//! Writes `fixtures/synthetic-session.srf.hex`: an annotated hex dump of a
//! short SRF (synthetic, made-up) session.
//!
//!     cargo run -p radar-ingest --example make_srf_fixture

use std::fmt::Write as _;

use radar_ingest::srf::build;

fn main() {
    let t0: i64 = 1_760_000_000_000;
    let frames: Vec<(&str, Vec<u8>)> = vec![
        (
            "zone changed: synthetic-zone",
            build::zone_changed(t0, "synthetic-zone"),
        ),
        (
            "player at (0, 0, 0), heading 0",
            build::player(t0, [0.0, 0.0, 0.0], Some(0.0)),
        ),
        (
            "cube 1 spawned at (10, 20, 0)",
            build::cube_spawned(t0 + 100, 1, [10.0, 20.0, 0.0]),
        ),
        (
            "cube 1 spawned again (duplicate)",
            build::cube_spawned(t0 + 100, 1, [10.0, 20.0, 0.0]),
        ),
        (
            "static spawn point 900 (must never show)",
            build::spawn_point(t0 + 150, 900, [60.0, 60.0, 0.0]),
        ),
        (
            "cube 2 spawned at (-40, -10, 2)",
            build::cube_spawned(t0 + 200, 2, [-40.0, -10.0, 2.0]),
        ),
        (
            "player moves to (5, 5, 0), heading 45",
            build::player(t0 + 500, [5.0, 5.0, 0.0], Some(45.0)),
        ),
        ("cube 1 seen", build::cube_seen(t0 + 1_000, 1)),
        ("cube 2 seen", build::cube_seen(t0 + 1_000, 2)),
        ("cube 1 collected", build::cube_removed(t0 + 2_000, 1, true)),
        (
            "cube 2 despawned",
            build::cube_removed(t0 + 3_000, 2, false),
        ),
    ];
    let mut out = String::from(
        "# SRF synthetic session — made-up data in a made-up format, NOT AION 2.\n\
         # Generated by examples/make_srf_fixture.rs. Hex bytes; '#' starts a comment.\n",
    );
    for (what, bytes) in frames {
        writeln!(out, "# {what}").unwrap();
        let hex: Vec<String> = bytes.iter().map(|b| format!("{b:02x}")).collect();
        writeln!(out, "{}", hex.join(" ")).unwrap();
    }
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/fixtures/synthetic-session.srf.hex"
    );
    std::fs::write(path, out).expect("write fixture");
    println!("wrote {path}");
}
